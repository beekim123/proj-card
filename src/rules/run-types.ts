import type { Card, GameState, GemForm, ToolType } from './types';

export type NormalMonster = 'chest' | 'soldier' | 'bear';
export type MonsterKey = NormalMonster | 'clock' | 'dragon';
export type FightType = 'normal' | 'elite' | 'boss';
export type AdventureHandLimit = 7 | 8;
export type RuleId = 'bite' | 'hug' | 'wind' | 'bell';
export type RelicId = 'same' | 'once' | 'white' | 'rainbow' | 'heart' | 'grow';
export type RunPhase = 'relic' | 'battle' | 'loot' | 'victory' | 'defeat';

export interface FightConfig {
  type: FightType;
  monster?: MonsterKey;
  hp: number;
  countdown: number;
  healFull?: boolean;
  handUp?: number;
}

export interface MonsterState {
  key: MonsterKey;
  hp: number;
  maxHp: number;
  countdown: number;
  maxCountdown: number;
  broken: boolean;
  /** HP before the first play of the current turn. Never replaced on breaking. */
  turnStartHp: number;
  /** The raw ratio, not its rounded display value. Zero until broken. */
  overkill: number;
  rule: RuleId | 'layers';
  layer: 1 | 2 | 3;
  wind: number;
  maxWind: number;
  woundDown: boolean;
}

export interface FightSummary {
  fight: number;
  monster: MonsterKey;
  won: boolean;
  turns: number;
  damage: number;
  overkill: number;
}

export interface RunStats {
  /** Finished turns. Abandoning a battle also counts its unfinished current turn. */
  turns: number;
  bestTurn: number;
  bestFight: number;
  maxOverkill: number;
  totalDamage: number;
  fights: FightSummary[];
}

export interface RunRecords {
  played: number;
  wins: number;
  /** 1–6 for reached fights; 7 for a completed adventure, 0 before playing. */
  farthest: number;
  bestTurn: number;
  maxOverkill: number;
}

export interface RunRecordFlags {
  farthest: boolean;
  bestTurn: boolean;
  maxOverkill: boolean;
}

export interface RunResult {
  outcome: 'victory' | 'defeat';
  reason: 'boss' | 'hearts' | 'abandoned';
  fight: number;
  monster: MonsterKey;
  totalTurns: number;
  bestTurn: number;
  bestFight: number;
  maxOverkill: number;
  totalDamage: number;
  gemForms: [GemForm, GemForm, GemForm];
  extraCards: Card[];
  newRecords: RunRecordFlags;
  /** Stops repeated settlement callbacks from counting this run twice. */
  recordsApplied: boolean;
}

/** Game snapshots live in game.hist; these paired entries restore adventure data. */
export interface RunUndo {
  monster: MonsterState;
  stats: RunStats;
}

/** Portable JSON state. Its one RNG state lives at game.rngState. */
export interface RunState {
  cards: Card[];
  hearts: number;
  maxHearts: number;
  relicOptions: RelicId[];
  relic: RelicId | null;
  relics: RelicId[];
  handLimit: AdventureHandLimit;
  /** One-based fight number. */
  fight: number;
  /** All six identities are decided at creation using the same RNG as cards. */
  monsters: MonsterKey[];
  monster: MonsterState;
  game: GameState;
  phase: RunPhase;
  /** Fixed on entry to loot; never regenerated by reads or reloads. */
  loot: ToolType[];
  stats: RunStats;
  hist: RunUndo[];
  result: RunResult | null;
}
